#!/usr/bin/env elixir
# Builds the site's social image: site/public/og.svg (the source, text as Geist outlines so it
# renders the same anywhere) and site/public/og.png (1200×630, rendered from it by rsvg-convert).
#
# Needs hb-view (HarfBuzz) and rsvg-convert on PATH, and Geist as a TTF. The site only ships
# Geist as woff2 (@fontsource-variable/geist), which neither tool reads, so decompress it once:
#
#   uvx --with brotli --from fonttools fonttools ttLib.woff2 decompress \
#     site/node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2 -o /tmp/Geist.ttf
#   elixir docs/experiments/2026-11-03-website/deploy/og.exs --font /tmp/Geist.ttf
#
# Text is shaped by HarfBuzz (kerning included) at the weight given, then tracked like the site's
# headings (letter-spacing in em). Colours are the site's dark tokens (src/styles/global.css) and
# the mark's brand hex (app/src-tauri/icons/source/icon.svg).

defmodule OG do
  @w 1200
  @h 630
  @bg "#0a0a0a"
  @fg "#fafafa"
  @muted "#a1a1a1"
  @brand "#f28a2e"
  # The mark, [x, y, w, h] in a 50×60 box (site/src/components/Mark.astro).
  @tiles [{0, 0, 16, 22}, {34, 0, 16, 60}, {0, 25, 31, 16}, {8, 44, 23, 16}]

  def run(argv) do
    {opts, _} = OptionParser.parse!(argv, strict: [font: :string, out: :string])
    font = Keyword.get(opts, :font) || die("--font path/to/Geist.ttf is required (see the header)")
    out = Keyword.get(opts, :out, Path.expand("../../../../site/public", __DIR__))
    File.exists?(font) || die("no font at #{font}")

    left = 80
    word = text(font, "wordmark", "yaah", size: 60, weight: 600, tracking: -0.025, color: @fg)
    line1 = text(font, "h1", "Agents answer", size: 96, weight: 600, tracking: -0.035, color: @fg)
    line2 = text(font, "h2", "with interface.", size: 96, weight: 600, tracking: -0.035, color: @fg)
    sub = text(font, "sub", "A desktop harness for coding agents.", size: 28, weight: 400, tracking: 0, color: @muted)
    url = text(font, "url", "filipecabaco.github.io/yaah", size: 24, weight: 500, tracking: 0, color: @muted)

    # The mark at 6×: 300×360, right-aligned to the same 80 px margin, centred vertically.
    scale = 6
    mark_x = @w - left - 50 * scale
    mark_y = div(@h - 60 * scale, 2)

    svg = """
    <svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="#{@w}" height="#{@h}" viewBox="0 0 #{@w} #{@h}">
    <!-- yaah social image. Generated by docs/experiments/2026-11-03-website/deploy/og.exs; text is Geist, outlined. -->
    <rect width="#{@w}" height="#{@h}" fill="#{@bg}"/>
    #{place(word, left, 140)}
    #{place(line1, left, 322)}
    #{place(line2, left, 424)}
    #{place(sub, left, 508)}
    #{place(url, left, 552)}
    <g transform="translate(#{mark_x} #{mark_y}) scale(#{scale})">
    #{Enum.map_join(Enum.with_index(@tiles), "\n", fn {{x, y, w, h}, i} -> ~s(<rect x="#{x}" y="#{y}" width="#{w}" height="#{h}" rx="5" fill="#{if i == 2, do: @brand, else: @fg}"/>) end)}
    </g>
    </svg>
    """

    File.mkdir_p!(out)
    svg_path = Path.join(out, "og.svg")
    png_path = Path.join(out, "og.png")
    File.write!(svg_path, svg)
    {_, 0} = System.cmd("rsvg-convert", ["--width", "#{@w}", "--height", "#{@h}", "-o", png_path, svg_path])

    for {name, t} <- [wordmark: word, h1: line1, h2: line2, sub: sub, url: url] do
      IO.puts("#{name}: #{Float.round(t.width, 1)} px wide, ends at x=#{Float.round(left + t.width, 1)}")
    end

    IO.puts("wrote #{svg_path} and #{png_path}")
  end

  # Shape `str` with hb-view and return its glyph defs and uses, ids prefixed so several can share
  # one document, with letter-spacing applied by moving each glyph.
  defp text(font, id, str, size: size, weight: weight, tracking: tracking, color: color) do
    args = [
      "--font-file=#{font}",
      "--variations=wght=#{weight}",
      "--font-size=#{size}",
      "--output-format=svg",
      "--margin=0",
      "--foreground=#{color}",
      "--background=#00000000",
      str
    ]

    {svg, 0} = System.cmd("hb-view", args)
    [_, width] = Regex.run(~r/<svg[^>]* width="([\d.]+)"/, svg)
    [defs] = Regex.run(~r/<defs>.*<\/defs>/s, svg)
    defs = String.replace(defs, ~s(id="glyph-), ~s(id="#{id}-glyph-))
    shift = tracking * size

    {uses, {count, baseline}} =
      Regex.scan(~r/<use xlink:href="#glyph-([\d-]+)" x="([-\d.]+)" y="([-\d.]+)"\/>/, svg)
      |> Enum.map_reduce({0, nil}, fn [_, glyph, x, y], {i, _} ->
        x = num(x) + i * shift
        {~s(<use xlink:href="##{id}-glyph-#{glyph}" x="#{fmt(x)}" y="#{y}"/>), {i + 1, num(y)}}
      end)

    %{
      defs: defs,
      uses: Enum.join(uses, "\n"),
      color: color,
      baseline: baseline,
      width: num(width) + max(count - 1, 0) * shift
    }
  end

  # Put a shaped text's baseline at (x, y).
  defp place(t, x, y) do
    """
    <g transform="translate(#{x} #{fmt(y - t.baseline)})">
    #{t.defs}
    <g fill="#{t.color}">
    #{t.uses}
    </g>
    </g>
    """
  end

  defp num(s) do
    case Float.parse(s) do
      {f, _} -> f
      :error -> die("not a number: #{s}")
    end
  end

  defp fmt(f), do: :erlang.float_to_binary(f * 1.0, decimals: 3)

  defp die(msg) do
    IO.puts(:stderr, "og.exs: #{msg}")
    System.halt(1)
  end
end

OG.run(System.argv())
